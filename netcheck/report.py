"""Turns check results into a console table, a CSV file and a self-contained HTML page."""

from __future__ import annotations

import csv
import html
from collections.abc import Sequence
from datetime import datetime
from pathlib import Path
from string import Template

from netcheck.scanner import DeviceResult, Status

CSV_FIELDS = [
    "name",
    "host",
    "type",
    "critical",
    "status",
    "ping",
    "latency_ms",
    "open_ports",
    "closed_ports",
    "checked_at",
]


def result_row(result: DeviceResult) -> dict[str, str]:
    latency = result.ping.latency_ms
    return {
        "name": result.device.name,
        "host": result.device.host,
        "type": result.device.type,
        "critical": "yes" if result.device.critical else "no",
        "status": result.status.value,
        "ping": "reply" if result.ping.reachable else "no reply",
        "latency_ms": "" if latency is None else f"{latency:g}",
        "open_ports": " ".join(str(p) for p in result.open_ports),
        "closed_ports": " ".join(str(p) for p in result.closed_ports),
        "checked_at": result.checked_at.isoformat(timespec="seconds"),
    }


def summarize(results: Sequence[DeviceResult]) -> dict[str, int]:
    return {status.value: sum(1 for r in results if r.status is status) for status in Status}


def summary_line(results: Sequence[DeviceResult]) -> str:
    counts = summarize(results)
    return f"{len(results)} device(s): " + ", ".join(f"{n} {s}" for s, n in counts.items())


def _ports_text(result: DeviceResult) -> str:
    parts = []
    if result.open_ports:
        parts.append("open " + ",".join(str(p) for p in result.open_ports))
    if result.closed_ports:
        parts.append("closed " + ",".join(str(p) for p in result.closed_ports))
    return "; ".join(parts) or "-"


def format_table(results: Sequence[DeviceResult]) -> str:
    headers = ["STATUS", "NAME", "HOST", "PING", "PORTS"]
    rows = []
    for r in results:
        ping = (
            f"{r.ping.latency_ms:g} ms"
            if r.ping.latency_ms is not None
            else ("reply" if r.ping.reachable else "-")
        )
        name = r.device.name + (" *" if r.device.critical else "")
        rows.append([r.status.value, name, r.device.host, ping, _ports_text(r)])

    widths = [max(len(str(row[i])) for row in [headers, *rows]) for i in range(len(headers))]
    lines = [
        "  ".join(cell.ljust(widths[i]) for i, cell in enumerate(row)).rstrip()
        for row in [headers, *rows]
    ]
    lines.insert(1, "  ".join("-" * w for w in widths))
    return "\n".join(lines)


def write_csv(results: Sequence[DeviceResult], path: str | Path) -> Path:
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", newline="", encoding="utf-8") as handle:
        writer = csv.DictWriter(handle, fieldnames=CSV_FIELDS)
        writer.writeheader()
        writer.writerows(result_row(r) for r in results)
    return path


