def render_html(results: Sequence[DeviceResult], title: str) -> str:
    esc = html.escape
    rows = []
    for r in results:
        row = result_row(r)
        ping = f"{row['latency_ms']} ms" if row["latency_ms"] else row["ping"]
        critical = " *" if r.device.critical else ""
        rows.append(
            f'<tr><td><span class="badge {r.status.value.lower()}">{r.status.value}</span></td>'
            f"<td>{esc(r.device.name)}{critical}</td><td>{esc(r.device.host)}</td>"
            f"<td>{esc(r.device.type)}</td><td>{esc(ping)}</td>"
            f"<td>{esc(row['open_ports']) or '<span class=muted>-</span>'}</td>"
            f"<td>{esc(row['closed_ports']) or '<span class=muted>-</span>'}</td></tr>"
        )
    cards = "".join(
        f'<div class="card {status.lower()}"><strong>{count}</strong>{status}</div>'
        for status, count in summarize(results).items()
    )
    return _PAGE.substitute(
        title=esc(title),
        checked_at=datetime.now().strftime("%Y-%m-%d %H:%M"),
        summary=esc(summary_line(results)),
        cards=cards,
        rows="\n".join(rows),
    )


def write_html(results: Sequence[DeviceResult], path: str | Path, title: str) -> Path:
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(render_html(results, title), encoding="utf-8")
    return path
